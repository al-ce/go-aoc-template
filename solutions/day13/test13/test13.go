var (
	partOneAnswer = "480"
	partTwoAnswer = "unknown"
)

type SolutionFunc func([]string) string

func runTest(lines []string, part int, solution SolutionFunc, expected string) {
	fmt.Printf("Part %d: ", part)
	result := solution(lines)
	if result != expected {
		fmt.Printf("\033[31m%v\033[0m (expected \033[32m%v\033[0m)\n", result, expected)
	} else {
		fmt.Printf("\033[32m%v\033[0m\n", result)
	}
}

func main() {
	runTest(lines, 1, day13.PartOne, partOneAnswer)
	runTest(lines2, 2, day13.PartTwo, partTwoAnswer)
}
